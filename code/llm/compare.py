"""Agreement between the hand-made transcriptions and model readings (recorded fixtures).

This is agreement between two readings of the same picture, **not** ground truth: both can be wrong in the same way. The
tool only reports; it never changes a transcription. Run: python3 code/llm/compare.py  (writes
code/evaluation/screenshot_agreement.md)."""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from llm.fixtures import FIXTURE_ROOT, parse_fixture, path_for   # noqa: E402

STEP = "screenshot_transcribe"
OUT = Path(__file__).resolve().parents[1] / "evaluation" / "screenshot_agreement.md"


def _norm_ids(values) -> set:
    return {v.strip().lower() for v in values}


def _selected(data: dict) -> dict:
    return next(r for r in data["rows"] if r["selected"])


def diff_readings(a: dict, b: dict) -> list:
    """Field-level disagreements between two validated transcriptions (a = transcribed, b = model)."""
    out = []
    sa, sb = _selected(a), _selected(b)
    for f in ("record_type", "resource_id"):
        if sa[f] != sb[f]:
            out.append((f"selected row {f}", sa[f], sb[f]))
    for f in sa["facts"]:
        if sa["facts"][f] != sb["facts"][f] and not (f == "status"):          # status is free text: compared below
            out.append((f"selected row facts.{f}", sa["facts"][f], sb["facts"][f]))
    if (sa["facts"]["status"] or "").strip().lower() != (sb["facts"]["status"] or "").strip().lower():
        out.append(("selected row facts.status (free text)", sa["facts"]["status"], sb["facts"]["status"]))
    ia, ib = _norm_ids(sa["identifiers"]), _norm_ids(sb["identifiers"])
    if ia != ib:
        out.append(("selected row identifiers", sorted(ia - ib) or "-", sorted(ib - ia) or "-"))
    ra = {(r["record_type"], r["resource_id"]) for r in a["rows"] if not r["selected"] and r["resource_id"]}
    rb = {(r["record_type"], r["resource_id"]) for r in b["rows"] if not r["selected"] and r["resource_id"]}
    if ra != rb:
        out.append(("other rows with ids", sorted(ra - rb) or "-", sorted(rb - ra) or "-"))
    return out


def compare_all(root: Path = FIXTURE_ROOT, step: str = STEP) -> dict:
    """-> {key: list of disagreements | 'no recorded reading'}"""
    out = {}
    tdir = Path(root) / "transcribed" / step
    for p in sorted(tdir.glob("*.md")):
        key = p.stem
        rec_path = path_for(root, "recorded", step, key)
        if not rec_path.exists():
            out[key] = "no recorded reading"
            continue
        a = parse_fixture(p.read_text(encoding="utf-8"), "transcribed").data
        b = parse_fixture(rec_path.read_text(encoding="utf-8"), "recorded").data
        out[key] = diff_readings(a, b)
    return out


def render(result: dict) -> str:
    done = {k: v for k, v in result.items() if v != "no recorded reading"}
    agree = sum(1 for v in done.values() if not v)
    L = ["# Agreement between transcriptions and model readings (generated by `python3 code/llm/compare.py`)", "",
         "Two readings of the same screenshots: the assistant's hand transcription (`transcribed`) and a model's answer "
         "(`recorded`, from a real API call). **This is agreement between two readings, not ground truth.** Transcriptions are "
         "never overwritten by this tool.", "",
         f"Screenshots with both readings: {len(done)} of {len(result)}; identical on every compared field: {agree}.", ""]
    if not done:
        L += ["No recorded reading exists yet: no live call has been made.", ""]
    for key, diffs in result.items():
        if diffs == "no recorded reading":
            L.append(f"- `{key}`: no recorded reading")
        elif not diffs:
            L.append(f"- `{key}`: identical")
        else:
            L.append(f"- `{key}`: {len(diffs)} disagreement(s)")
            for field, a, b in diffs:
                L.append(f"  - {field}: transcription `{a}` / model `{b}`")
    return "\n".join(L) + "\n"


def main() -> int:
    text = render(compare_all())
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
