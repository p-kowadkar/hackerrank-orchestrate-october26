"""The run manifest and the usage report, both derived from the run that wrote output.csv.

`python3 code/main.py` writes `code/evaluation/run_manifest.md` and `code/evaluation/usage_report.md` together with
`output.csv`, so the usage report always describes the run that produced the output file: the manifest carries the md5 of
output.csv, and a test checks that md5, that the manifest's call count equals the ledger rows of its run id, and that the
usage report equals a fresh rendering of manifest plus ledger. Nothing in the report is typed by hand.
"""
from __future__ import annotations

import hashlib
import re
from collections import Counter, defaultdict
from pathlib import Path

from .usage import Ledger

EVAL_DIR = Path(__file__).resolve().parents[1] / "evaluation"
MANIFEST_PATH = EVAL_DIR / "run_manifest.md"
USAGE_REPORT_PATH = EVAL_DIR / "usage_report.md"


def md5_of(path: Path) -> str:
    return hashlib.md5(Path(path).read_bytes()).hexdigest()


# ------------------------------------------------------------------------------------------------ the manifest
def build_manifest(*, command: str, output_path: Path, n_rows: int, mode: str, replay_origins: str, run_id: str,
                   model: str, reader, fallback, unclear_texts: int, ledger: Ledger, repo_root: Path) -> dict:
    shots = []
    for c in reader.calls:
        shots.append({"file_id": c.key, "origin": c.origin, "model": c.model or "-"})
    for fid, _why in reader.unread:
        shots.append({"file_id": fid, "origin": "unread", "model": "-"})
    shots.sort(key=lambda s: int(s["file_id"].split("_")[1]))
    return {"command": command, "output_file": str(Path(output_path).relative_to(repo_root)), "output_rows": n_rows,
            "output_md5": md5_of(output_path), "llm_mode": mode, "replay_origins": replay_origins, "run_id": run_id,
            "model": model or "-", "api_calls": len(ledger.rows(run_id)), "intent_calls": len(fallback.calls),
            "unclear_texts": unclear_texts, "screenshots": shots}


def render_manifest(m: dict) -> str:
    L = ["# Run manifest", "", "Written by `python3 code/main.py` together with `output.csv`; it describes the run that produced that "
         "file. The usage report is rendered from this manifest and the usage ledger.", ""]
    for k in ("command", "output_file", "output_rows", "output_md5", "llm_mode", "replay_origins", "run_id", "model", "api_calls",
              "intent_calls", "unclear_texts"):
        L.append(f"- {k}: {m[k]}")
    L += ["", "## Screenshots", "", "| file | origin | model |", "|---|---|---|"]
    for s in m["screenshots"]:
        L.append(f"| {s['file_id']} | {s['origin']} | {s['model']} |")
    L.append("")
    return "\n".join(L)


def parse_manifest(text: str) -> dict:
    m = {}
    for line in text.splitlines():
        mt = re.match(r"^- (\w+): (.*)$", line)
        if mt:
            m[mt.group(1)] = mt.group(2)
    for k in ("output_rows", "api_calls", "intent_calls", "unclear_texts"):
        m[k] = int(m[k])
    m["screenshots"] = []
    for line in text.splitlines():
        mt = re.match(r"^\| (evidence_\d+) \| (\S+) \| (.*) \|$", line)
        if mt:
            m["screenshots"].append({"file_id": mt.group(1), "origin": mt.group(2), "model": mt.group(3)})
    return m


# --------------------------------------------------------------------------------------------- the usage report
def render_usage_report(m: dict, rows: list, other: list = ()) -> str:
    n = m["output_rows"]
    by_model = defaultdict(lambda: Counter())
    costs_missing = 0
    for r in rows:
        key = (r.provider, r.model)
        c = by_model[key]
        c["calls"] += 1
        c["invalid"] += r.outcome == "invalid"
        c["prompt"] += r.prompt_tokens
        c["completion"] += r.completion_tokens
        c["total"] += r.total_tokens
        if r.cost_usd is None:
            costs_missing += 1
        else:
            c["cost_known"] += 1
            c["cost"] += r.cost_usd
    tot = Counter()
    for c in by_model.values():
        tot.update(c)
    origins = Counter(s["origin"] for s in m["screenshots"])
    L = ["# Usage report", "",
         f"Generated by `python3 code/main.py` from `code/evaluation/run_manifest.md` and `code/evaluation/usage_ledger.md`; "
         "do not edit by hand (a test regenerates it and compares). Every figure is read from real API responses recorded in "
         "the ledger; nothing is estimated from text length or a price list.", "",
         "## The run that produced `output.csv`", "",
         f"- output: `{m['output_file']}`, {n} rows, md5 `{m['output_md5']}`",
         f"- command: `{m['command']}`",
         f"- model-backed steps: llm mode `{m['llm_mode']}`" + (f" (fixture origins: {m['replay_origins']})" if m["llm_mode"] == "replay" else ""),
         f"- run id: `{m['run_id']}`",
         f"- API calls in this run (ledger rows for the run id): **{len(rows)}**", ""]
    L += ["## How the 11 screenshots were read in this run", "",
          "| read from | screenshots |", "|---|---|"]
    meaning = {"transcribed": "stored transcription made by the assistant in a Claude Code session (not an API call; no usage)",
               "recorded": "stored answer of an earlier real API call", "live": "real API call in this run",
               "unread": "not read (no model, no fixture)"}
    for k in ("live", "recorded", "transcribed", "unread"):
        if origins.get(k):
            L.append(f"| {meaning[k]} | {origins[k]} |")
    if not m["screenshots"]:
        L.append("| none | 0 |")
    L += ["", f"Intent fallback: {m['intent_calls']} model answers used; {m['unclear_texts']} request texts were unclear to the rules.", ""]
    L += ["## Totals", "",
          "| provider | model | calls | invalid answers | input tokens | output tokens | total tokens | cost reported (USD) |",
          "|---|---|---|---|---|---|---|---|"]
    if not by_model:
        L.append("| none | none | 0 | 0 | 0 | 0 | 0 | 0 |")
    for (prov, model), c in sorted(by_model.items()):
        cost = f"{c['cost']:.6f}" if c["cost_known"] else "not reported"
        L.append(f"| {prov} | {model} | {c['calls']} | {c['invalid']} | {c['prompt']} | {c['completion']} | {c['total']} | {cost} |")
    if len(by_model) > 1:
        L.append(f"| all | all | {tot['calls']} | {tot['invalid']} | {tot['prompt']} | {tot['completion']} | {tot['total']} | "
                 f"{tot['cost']:.6f} |")
    L += ["", "| measure | value |", "|---|---|",
          f"| model calls | {tot['calls']} |", f"| input tokens | {tot['prompt']} |", f"| output tokens | {tot['completion']} |",
          f"| total tokens | {tot['total']} |",
          f"| average total tokens per request ({n} requests) | {tot['total'] / n:.2f} |",
          f"| total cost reported by the provider (USD) | {tot['cost']:.6f} |",
          f"| average cost per request (USD) | {tot['cost'] / n:.8f} |", ""]
    if costs_missing:
        L += [f"The provider reported no cost for {costs_missing} of {len(rows)} calls; the cost totals above cover only the calls "
              "that reported one. No cost was computed from a price list.", ""]
    if not rows:
        L += ["No model was called in this run, so every token and cost figure is zero. This is the state of the repository until a "
              "live run is made: the screenshots are read from the stored transcriptions above.", ""]
    if other:
        o_tok = sum(r.total_tokens for r in other)
        o_cost = sum(r.cost_usd for r in other if r.cost_usd is not None)
        L += ["## Other runs in the ledger (not part of the run above)", "",
              f"{len(other)} API calls in {len({r.run_id for r in other})} other run(s), {o_tok} tokens, {o_cost:.6f} USD reported. "
              "They were made but did not produce the submitted `output.csv`, so they are not in the totals above; they are listed here "
              "so that the money actually spent is not hidden.", ""]
    L += ["## Rules", "",
          "- Tokens and cost come only from the `usage` block of real API responses, written to the ledger when the response arrives.",
          "- A transcription made by hand is labelled `transcribed`, carries no usage, and can never enter the ledger.",
          "- The API key is read from `OPENROUTER_API_KEY` and is never written to any file; a real key is needed outside the "
          "development sandbox.", ""]
    return "\n".join(L)


def other_rows(ledger: Ledger, run_id: str) -> list:
    return [r for r in ledger.rows() if r.run_id != run_id]


def write_run_artifacts(manifest: dict, ledger: Ledger, manifest_path: Path = MANIFEST_PATH,
                        usage_path: Path = USAGE_REPORT_PATH) -> None:
    manifest_path.write_text(render_manifest(manifest), encoding="utf-8", newline="\n")
    usage_path.write_text(render_usage_report(manifest, ledger.rows(manifest["run_id"]), other_rows(ledger, manifest["run_id"])),
                          encoding="utf-8", newline="\n")


def main() -> int:
    """Re-render the usage report from the manifest and ledger on disk (the same function main.py uses)."""
    m = parse_manifest(MANIFEST_PATH.read_text(encoding="utf-8"))
    ledger = Ledger()
    USAGE_REPORT_PATH.write_text(render_usage_report(m, ledger.rows(m["run_id"]), other_rows(ledger, m["run_id"])), encoding="utf-8",
                                 newline="\n")
    print(f"wrote {USAGE_REPORT_PATH}")
    return 0
