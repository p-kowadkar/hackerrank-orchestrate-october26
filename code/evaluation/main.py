"""Evaluation entry point: python3 code/evaluation/main.py

Runs the pipeline on the 32 sample requests, scores it against dataset/sample_output.csv (the only golden data),
tags every discrepancy with a root cause, scores the hand-derived image/PDF expectations in a separate
"unverified" section, and backtests the ambiguity policy (omit, hybrid, guess). Writes sample_scorecard.md.
"""
from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from ghostaudit import model as m                      # noqa: E402
from ghostaudit.data import Dataset                    # noqa: E402
from ghostaudit.evidence import extract_links          # noqa: E402
from ghostaudit.paths import CODE_DIR, DATASET_DIR     # noqa: E402
from llm.offline import run_replay as run                    # noqa: E402
from ghostaudit.planner import PlanOptions             # noqa: E402
from score import (load_answers, load_derived, render_scorecard, score, score_derived,   # noqa: E402
                   visible_resource_ids)

EVAL_DIR = CODE_DIR / "evaluation"


def to_answers(results: dict) -> dict:
    return {cid: (r.status, r.steps) for cid, r in results.items()}


def make_classifier(visible: set, run_result):
    def classify(cid: str, d):
        mt = m.RID_RE.search(d.detail)
        rid = mt.group() if mt else None
        if d.kind == "STATUS":
            return "status follows from a step-level difference"
        if d.kind == "FIELD":
            return "evidence citation" if "evidence_id" in d.detail else "state"
        if rid and d.kind == "MISSING" and rid not in visible:
            return "id absent from all participant data"
        if rid and rid.startswith("account_"):
            asg = run_result.assignments.get(cid)
            if asg is not None and asg.how in ("guess", "ambiguous", "none", "tiebreak"):
                return f"account identity ({asg.how}, {len(asg.candidates)} candidates)"
            return "account identity"
        if d.kind == "ORDER":
            return "ordering"
        return ""
    return classify


def evaluate(ds: Dataset, ambiguity: str, verify_compliant: bool = False):
    opts = PlanOptions(ambiguity=ambiguity, verify_compliant_in_incomplete=verify_compliant)
    res = run(ds, ds.all_requests, opts)
    gold = load_answers(DATASET_DIR / "sample_output.csv")
    pred = to_answers({c: r for c, r in res.results.items() if c in gold})
    return res, pred, gold, score(pred, gold)


POLICIES = ("omit", "hybrid", "guess")          # conservative first: max() keeps the first of equals


def backtest_key(sc):
    """Fixed before the run: step-level F1, then exactly reproduced cases, then fewer wrong (extra) steps."""
    return (round(sc.step_prf()[2], 6), sc.exact_cases, -sc.fp)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--ambiguity", choices=("guess", "omit", "hybrid", "auto"), default="auto",
                    help="auto = run all three and keep whichever scores best on the samples (ties go to the more conservative)")
    ap.add_argument("--out", type=Path, default=EVAL_DIR / "sample_scorecard.md")
    args = ap.parse_args(argv)
    ds = Dataset()
    visible = visible_resource_ids(DATASET_DIR, extra_texts=[lk.resource_id for lk in extract_links(ds)])
    runs = {}
    for pol in POLICIES:
        res, pred, gold, sc = evaluate(ds, pol)
        runs[pol] = (res, pred, gold, sc)
    chosen = args.ambiguity if args.ambiguity != "auto" else max(runs, key=lambda k: backtest_key(runs[k][3]))
    res, pred, gold, sc = runs[chosen]
    classify = make_classifier(visible, res)
    sc = score(pred, gold, classify)
    tags = Counter(d.tag for d in sc.discrepancies)

    L = ["# Sample scorecard (generated by `python3 code/evaluation/main.py`)", "",
         "Headline numbers use **only** `dataset/sample_output.csv`. Hand-derived image/PDF expectations are in a",
         "separate, clearly unverified section below and are never included in these numbers.", "",
         render_scorecard(sc, f"Headline: 32 sample cases (ambiguity policy `{chosen}`)", tags), ""]
    L += ["## Ambiguity policy backtest (omit versus hybrid versus guess)", "",
          "Criterion fixed in advance: step-level F1, then exactly reproduced cases, then fewer extra steps; ties go to the "
          "more conservative policy (omit, then hybrid, then guess).", "",
          "| policy | step F1 | exact cases | extra steps (fp) | missing steps (fn) | status accuracy |", "|---|---|---|---|---|---|"]
    for pol, (_r, _p, _g, s) in runs.items():
        L.append(f"| {pol} | {s.step_prf()[2]:.4f} | {s.exact_cases}/{s.n_cases} | {s.fp} | {s.fn} | {s.status_correct}/{s.n_cases} |")
    gold_rids = {cid: {st["resource_id"] for st in g[1]} for cid, g in gold.items()}
    L += ["", f"Winner under the criterion: `{max(runs, key=lambda k: backtest_key(runs[k][3]))}`.", ""]
    for pol in POLICIES:
        r_ = runs[pol][0]
        made = [(cid, a.resource_id, kind) for kind, table in (("account", r_.assignments), ("analytics", r_.analytics))
                for cid, a in table.items() if cid in gold and a.how == "guess" and a.resource_id]
        right = [x for x in made if x[1] in gold_rids[x[0]]]
        omitted = [cid for cid, a in r_.assignments.items() if cid in gold and a.how == "ambiguous"]
        L.append(f"- policy `{pol}`: guesses made on sample cases: {len(made)}, correct: {len(right)}; "
                 f"ambiguous accounts left out: {len(omitted)}")
    L += ["", "Sample size is small, so the margin deserves caution. Across all 540 deletion cases the `guess` policy makes "
          f"{sum(1 for a in runs['guess'][0].assignments.values() if a.how == 'guess')} account guesses and "
          f"{sum(1 for a in runs['guess'][0].analytics.values() if a.how == 'guess')} analytics guesses; the samples cannot "
          "say how accurate those are outside the samples.", ""]
    ties = [u for u in res.tiebreak_uses if u.case_id in gold]
    L += ["## Status/worker-result tiebreak uses", "",
          f"- all cases (samples + eval, matching context): {len(res.tiebreak_uses)} uses, "
          f"{sum(1 for u in res.tiebreak_uses if u.resolved)} narrowed to one account",
          f"- sample cases: {len(ties)} uses, {sum(1 for u in ties if u.resolved)} narrowed to one account", ""]
    derived = load_derived(EVAL_DIR / "derived_cases.md")
    L += ["## UNVERIFIED: hand-derived image/PDF cases (not ground truth, excluded from headline)", "",
          "Predictions below read the screenshots from the stored transcriptions (`code/llm/fixtures/transcribed/`, the assistant's "
          "own reading of the images). The expectations in `derived_cases.md` are *also* the assistant's reading of the same "
          "images, so agreement here shows that the reader, the mapping and the planner are wired together correctly; it does "
          "**not** show that the readings are right. Treat it as consistency between two readings by one reader, not as accuracy.", ""]
    if derived:
        L += ["| case | status expected / predicted | required steps found | confidence |", "|---|---|---|---|"]
        for r in score_derived(to_answers(res.results), derived):
            L.append(f"| {r['case_id']} | {r['expected']} / {r['predicted']} | {r['found']}/{r['required']} | {r['confidence']} |")
    else:
        L.append("(no derived cases file)")
    args.out.write_text("\n".join(L) + "\n", encoding="utf-8")
    p, r_, f1 = sc.step_prf()
    print(f"policy={chosen}  status {sc.status_correct}/{sc.n_cases}  step P/R/F1 {p:.3f}/{r_:.3f}/{f1:.3f}  "
          f"exact cases {sc.exact_cases}/{sc.n_cases}  discrepancies {len(sc.discrepancies)}")
    for pol, (_r, _p, _g, s) in runs.items():
        print(f"  backtest {pol}: F1 {s.step_prf()[2]:.4f} exact {s.exact_cases} fp {s.fp} fn {s.fn}")
    print("  root causes:", dict(tags))
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
